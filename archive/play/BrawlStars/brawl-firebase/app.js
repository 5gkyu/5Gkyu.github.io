function getCharRole(char) {
  if (!char) return "";
  const ROLE_TAGS = ["タンク", "アサシン", "シューター", "投げ", "召喚物"];
  if (Array.isArray(char.tags)) {
    for (const t of char.tags) {
      if (ROLE_TAGS.includes(t)) return t;
    }
  }
  const name = (char.name || "").trim();
  if (BRAWLER_ROLE_MAP[name]) return BRAWLER_ROLE_MAP[name];
  const lowerName = name.toLowerCase();
  for (const [k, v] of Object.entries(BRAWLER_ROLE_MAP)) {
    if (k.toLowerCase() === lowerName) return v;
  }
  if (char.class_ja) {
    const cj = char.class_ja.trim();
    if (cj === "タンク" || cj === "アサシン") return cj;
    if (cj === "スナイパー" || cj === "アタッカー" || cj === "コントローラー" || cj === "サポート") return "シューター";
    if (cj === "グレネーディア") return "投げ";
  }
  return "";
}

function getCharRarityLevelValue(char) {
  if (!char) return 2;
  if (char.rarity_id != null) return Number(char.rarity_id);
  const hex = (char.rare || "").toLowerCase();
  if (RARITY_HEX_TO_LEVEL[hex]) return RARITY_HEX_TO_LEVEL[hex];
  return 2;
}

