// キャラクターの弾の太さ情報（表示テキスト、ソート用数値、段別items）を取得
function getCharBulletWidthInfo(char) {
  if (!char) return { items: ["-"], text: "-", num: 0.0 };

  // 1. キャラクターデータ自身に bullet_width_num があれば最優先で使用
  if (char.bullet_width_num !== undefined && char.bullet_width_num !== null) {
    const text = char.bullet_width || String(char.bullet_width_num);
    return {
      items: [text],
      text: text,
      num: Number(char.bullet_width_num)
    };
  }

  // 2. 辞書マップからの参照（フォールバック）
  const name = (char.name || "").trim();
  const mapInfo = BRAWLER_BULLET_WIDTH_MAP[name];
  if (mapInfo) {
    const items = mapInfo.items && mapInfo.items.length > 0 ? mapInfo.items : [mapInfo.text || "-"];
    return {
      items: items,
      text: mapInfo.text || items[0] || "-",
      num: typeof mapInfo.num === "number" ? mapInfo.num : 0.0
    };
  }
  const w = char.bullet_width || "-";
  const numMatch = String(w).match(/\d+(\.\d+)?/);
  const n = numMatch ? parseFloat(numMatch[0]) : 0.0;
  return { items: [w], text: w, num: n };
}

// キャラクターの射程情報（items配列、詳細解説、ソート用実効値）を取得
function getCharRangeInfo(char) {
  if (!char) return { effective: 0, range: 0, items: ["-"], mainText: "-", subText: null, detail: null };

  // 1. キャラクターデータ自身に range_effective があれば最優先で使用
  if (char.range_effective !== undefined && char.range_effective !== null) {
    const items = Array.isArray(char.range_items) && char.range_items.length > 0 ? char.range_items : [String(char.range_effective)];
    return {
      effective: Number(char.range_effective),
      range: Number(char.range_effective),
      items: items,
      mainText: items[0] || "-",
      subText: items[1] || null,
      detail: char.range_detail || null
    };
  }

  // 2. 辞書マップからの参照（フォールバック）
  const name = (char.name || "").trim();
  const mapInfo = BRAWLER_RANGE_MAP[name];
  if (mapInfo) {
    const items = mapInfo.items && mapInfo.items.length > 0 ? mapInfo.items : ["-"];
    return {
      effective: mapInfo.effective,
      range: mapInfo.effective,
      items: items,
      mainText: items[0] || "-",
      subText: items[1] || null,
      detail: mapInfo.detail
    };
  }

  const rawRange = (char.range !== undefined && char.range !== null) ? Number(char.range) : 0;
  const rawText = rawRange >= 0 ? String(rawRange) : "-";
  return {
    effective: rawRange,
    range: rawRange,
    items: [rawText],
    mainText: rawText,
    subText: null,
    detail: char.range_detail || null
  };
}
// 小数値をブロスタ標準の分数（12分率/300分率）に正規化
function normalizeGameFraction(num) {
  const floor = Math.floor(num);
  const frac = num - floor;
  const steps = Math.round(frac * 12);
  return floor + (steps / 12);
}

// ブロスタ標準の美しい小数文字列（.0, .33, .67, .50, .25, .17, .83 等）にフォーマット
function formatEffectiveReachVal(val) {
  const rounded = Math.round(val * 100) / 100;
  const floor = Math.floor(rounded);
  const frac = Math.round((rounded - floor) * 100);
  if (frac === 0) return floor + ".0";
  if (frac === 33 || frac === 34) return floor + ".33";
  if (frac === 66 || frac === 67) return floor + ".67";
  if (frac === 16 || frac === 17) return floor + ".17";
  if (frac === 83 || frac === 84) return floor + ".83";
  if (frac === 25) return floor + ".25";
  if (frac === 50) return floor + ".50";
  if (frac === 75) return floor + ".75";
  return rounded.toFixed(2);
}

// キャラクターの実射程情報（各段の射程 ＋ 各段の弾の太さ/2）を取得
function getCharEffectiveReachInfo(char) {
  if (!char) return { effective: 0, items: ["-"], mainText: "-" };
  const rangeInfo = getCharRangeInfo(char);
  const widthInfo = getCharBulletWidthInfo(char);

  if (rangeInfo.effective === null || rangeInfo.effective === undefined || rangeInfo.items[0] === "-") {
    return { effective: 0, items: ["-"], mainText: "-" };
  }

  const charName = (char.name || "").trim();

  // すでに射程値に爆風・水たまり・特殊効果半径が完全包含されているキャラ（二重加算防止）
  const ALREADY_INCLUDES_BLAST = ["ダイナマイク", "バーリー", "ティック", "ラリー＆ローリー", "ベリー", "ウィロー", "スクウィーク"];

  const reachItems = rangeInfo.items.map((it, idx) => {
    if (!it || it === "-") return "-";

    if (ALREADY_INCLUDES_BLAST.includes(charName)) {
      return it;
    }

    const match = String(it).match(/^([\d.]+)(.*)$/);
    if (!match) return it;
    const baseRange = parseFloat(match[1]);
    const suffix = match[2] || "";

    // その段に対応する弾の太さを取得（なければ0段目の太さを使用）
    const widthItemText = (widthInfo.items && (widthInfo.items[idx] || widthInfo.items[0])) || "-";
    const wMatch = String(widthItemText).match(/\d+(\.\d+)?/);
    const rowWidthNum = wMatch ? parseFloat(wMatch[0]) : 0.0;

    if (rowWidthNum <= 0) return it;

    // 内部Radius値（300分率）に基づく正確な半径への変換
    let radius = 0;
    if (Math.abs(rowWidthNum - 3.33) < 0.02) radius = 5 / 3;          // Radius 500
    else if (Math.abs(rowWidthNum - 3.00) < 0.02) radius = 1.5;       // Radius 450
    else if (Math.abs(rowWidthNum - 2.67) < 0.02) radius = 4 / 3;     // Radius 400
    else if (Math.abs(rowWidthNum - 1.67) < 0.02) radius = 5 / 6;     // Radius 250
    else if (Math.abs(rowWidthNum - 1.50) < 0.02) radius = 0.75;      // Radius 225
    else if (Math.abs(rowWidthNum - 1.33) < 0.02) radius = 2 / 3;     // Radius 200
    else if (Math.abs(rowWidthNum - 1.13) < 0.02) radius = 17 / 30;   // Radius 170
    else if (Math.abs(rowWidthNum - 1.00) < 0.02) radius = 0.5;       // Radius 150
    else if (Math.abs(rowWidthNum - 0.83) < 0.02) radius = 5 / 12;    // Radius 125
    else if (Math.abs(rowWidthNum - 0.73) < 0.02) radius = 11 / 30;   // Radius 110
    else if (Math.abs(rowWidthNum - 0.67) < 0.02) radius = 1 / 3;     // Radius 100
    else if (Math.abs(rowWidthNum - 0.53) < 0.02) radius = 4 / 15;    // Radius 80
    else if (Math.abs(rowWidthNum - 0.47) < 0.02) radius = 7 / 30;    // Radius 70
    else if (Math.abs(rowWidthNum - 0.40) < 0.02) radius = 0.2;       // Radius 60
    else if (Math.abs(rowWidthNum - 0.33) < 0.02) radius = 1 / 6;     // Radius 50
    else if (Math.abs(rowWidthNum - 0.27) < 0.02) radius = 2 / 15;    // Radius 40
    else radius = rowWidthNum / 2;

    const eff = normalizeGameFraction(baseRange) + radius;
    let labelSuffix = suffix;
    if (charName === "スプラウト") {
      if (suffix.includes("反射")) labelSuffix = " (反射爆風)";
      else if (suffix.includes("直撃")) labelSuffix = " (直撃爆風)";
    }
    return formatEffectiveReachVal(eff) + labelSuffix;
  });

  // ソート用実効値の算出（リコ・ラフス・ブロック・ピアス・キット・メグは通常時/直進/爪/メカの1段目をメイン実射程とする）
  let maxReach = 0;
  if (charName === "リコ" || charName === "ラフス" || charName === "ブロック" || charName === "ピアス" || charName === "キット" || charName === "メグ") {
    const m = String(reachItems[0]).match(/^([\d.]+)/);
    maxReach = m ? parseFloat(m[1]) : 0;
  } else {
    reachItems.forEach(it => {
      const m = String(it).match(/^([\d.]+)/);
      if (m) {
        const v = parseFloat(m[1]);
        if (v > maxReach) maxReach = v;
      }
    });
  }

  return {
    effective: maxReach,
    items: reachItems,
    mainText: reachItems[0] || "-",
    detail: "各段の射程 ＋ 各段の弾半径・爆風半径 ＝ 実射程"
  };
}

