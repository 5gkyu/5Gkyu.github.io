function getFilteredAndSortedCharacters() {
  const query = (searchInput.value || "").trim().toLowerCase();
  const sortKey = SORT_MODES[currentSortIndex].value;

  const filtered = characters.filter((c) => {
    // 検索ワード判定（名前・エイリアス・タグ内テキスト）
    const matchesSearch = !query ||
      (c.name && c.name.toLowerCase().includes(query)) ||
      (c.alias && c.alias.toLowerCase().includes(query)) ||
      (Array.isArray(c.tags) && c.tags.some(t => t.toLowerCase().includes(query)));

    // タグ絞り込み判定
    const matchesTag = !selectedTagFilter ||
      (selectedTagFilter === "__untagged__"
        ? (!Array.isArray(c.tags) || c.tags.length === 0)
        : (Array.isArray(c.tags) && c.tags.includes(selectedTagFilter)));

    // レアリティ絞り込み判定
    const charRarityLevel = getCharRarityLevelValue(c);
    const matchesRarity = !selectedRarityFilter || String(charRarityLevel) === String(selectedRarityFilter);

    // ロール絞り込み判定（パターン1: スピード/ヒール/バフやガジェット/ウルト破壊があれば親タグ不要で自動判定）
    let matchesRole = true;
    if (selectedRoleFilter) {
      const tags = Array.isArray(c.tags) ? c.tags : [];
      if (selectedRoleFilter === "サポート") {
        matchesRole = tags.includes("スピード") || tags.includes("ヒール") || tags.includes("バフ");
      } else if (selectedRoleFilter === "壁破壊") {
        matchesRole = tags.includes("ガジェットで破壊") || tags.includes("ウルトで破壊");
      } else if (selectedRoleFilter === "召喚物") {
        const SPAWN_BRAWLERS = ["ニタ", "ジェシー", "ペニー", "ミスターP", "ラリー＆ローリー", "タラ", "アッシュ", "チャーリー"];
        const name = (c.name || "").trim();
        matchesRole = SPAWN_BRAWLERS.includes(name) || (Array.isArray(c.tags) && c.tags.includes("召喚物"));
      } else {
        const charRole = getCharRole(c);
        matchesRole = (charRole === selectedRoleFilter) || (Array.isArray(c.tags) && c.tags.includes(selectedRoleFilter));
      }
    }

    // メタ対策絞り込み判定
    let matchesMeta = true;
    if (selectedMetaFilter) {
      const hasDirectTag = Array.isArray(c.tags) && c.tags.includes(selectedMetaFilter);
      if (hasDirectTag) {
        matchesMeta = true;
      } else {
        const META_FALLBACK_MAP = {
          "タンク対策": ["コレット", "シェリー", "グリフ", "サージ", "メイジー", "スパイク", "オーティス", "パール"],
          "投げ対策": ["モーティス", "エドガー", "ブロック", "ストゥー", "ファング", "ミコ", "リリー", "カゼ"],
          "アサシン対策": ["メイジー", "ジーン", "シェリー", "ゲイル", "サージ", "オーティス", "チャーリー", "タラ"],
          "召喚物対策": ["ペニー", "ジェシー", "ベル", "アンバー", "サンダーフロッグ"]
        };
        const fallbackList = META_FALLBACK_MAP[selectedMetaFilter] || [];
        const name = (c.name || "").trim();
        matchesMeta = fallbackList.includes(name);
      }
    }

    return matchesSearch && matchesTag && matchesRarity && matchesRole && matchesMeta;
  });

  return sortCharacterList(filtered, sortKey);
}

// キャラクター配列の共通ソート関数
function sortCharacterList(list, sortKey) {
  if (!list || list.length === 0) return list;

  list.sort((a, b) => {
    // 未実装キャラは常に最後尾に配置
    const unA = !!a.isUnreleased;
    const unB = !!b.isUnreleased;
    if (unA !== unB) return unA ? 1 : -1;

    if (sortKey) {
      let diff = 0;
      if (sortKey === "date-desc") {
        diff = parseAddedDate(b.addedDate) - parseAddedDate(a.addedDate);
      } else if (sortKey === "date-asc") {
        diff = parseAddedDate(a.addedDate) - parseAddedDate(b.addedDate);
      } else if (sortKey === "strength-desc") {
        diff = Number(b.tuyosa || 0) - Number(a.tuyosa || 0);
      } else if (sortKey === "strength-asc") {
        diff = Number(a.tuyosa || 0) - Number(b.tuyosa || 0);
      } else if (sortKey === "difficulty-desc") {
        diff = Number(b.difficulty || 1) - Number(a.difficulty || 1);
      } else if (sortKey === "difficulty-asc") {
        diff = Number(a.difficulty || 1) - Number(b.difficulty || 1);
      } else if (sortKey === "range-desc") {
        diff = Number(getCharRangeInfo(b).range || 0) - Number(getCharRangeInfo(a).range || 0);
      } else if (sortKey === "range-asc") {
        diff = Number(getCharRangeInfo(a).range || 0) - Number(getCharRangeInfo(b).range || 0);
      } else if (sortKey === "bullet-width-desc") {
        diff = getCharBulletWidthInfo(b).num - getCharBulletWidthInfo(a).num;
      } else if (sortKey === "bullet-width-asc") {
        diff = getCharBulletWidthInfo(a).num - getCharBulletWidthInfo(b).num;
      } else if (sortKey === "effective-reach-desc") {
        diff = Number(getCharEffectiveReachInfo(b).effective || 0) - Number(getCharEffectiveReachInfo(a).effective || 0);
      } else if (sortKey === "effective-reach-asc") {
        diff = Number(getCharEffectiveReachInfo(a).effective || 0) - Number(getCharEffectiveReachInfo(b).effective || 0);
      } else if (sortKey === "name-asc") {
        const kanaA = getKanaReading(a);
        const kanaB = getKanaReading(b);
        diff = kanaA.localeCompare(kanaB, "ja");
      }
      if (diff !== 0) return diff;

      if (sortKey !== "name-asc") {
        const rA = getCharRarityLevelValue(a);
        const rB = getCharRarityLevelValue(b);
        if (rA !== rB) return rA - rB;
      }
      const dateA = a.addedDate ? parseAddedDate(a.addedDate) : Infinity;
      const dateB = b.addedDate ? parseAddedDate(b.addedDate) : Infinity;
      if (dateA !== dateB) return dateA - dateB;
      return (a.order || 0) - (b.order || 0);
    } else {
      // デフォルト（レア度順）：低い順→高い順、同レア度内は実装日順（古い順）→ order順
      const rA = getCharRarityLevelValue(a);
      const rB = getCharRarityLevelValue(b);
      if (rA !== rB) return rA - rB;

      const dateA = a.addedDate ? parseAddedDate(a.addedDate) : Infinity;
      const dateB = b.addedDate ? parseAddedDate(b.addedDate) : Infinity;
      if (dateA !== dateB) return dateA - dateB;

      return (a.order || 0) - (b.order || 0);
    }
  });

  return list;
}

