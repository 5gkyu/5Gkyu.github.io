  // ---- モード別マップ一覧（50音順ソート）取得 ----
  function getSortedMapsForMode(modeId) {
    if (!mapData || !mapData.maps) return [];
    const list = mapData.maps.filter(m => m.modes && m.modes.includes(modeId));
    list.sort((a, b) => {
      const yomiA = MAP_YOMI_DICT[a.name] || a.yomi || a.name;
      const yomiB = MAP_YOMI_DICT[b.name] || b.yomi || b.name;
      return yomiA.localeCompare(yomiB, 'ja');
    });
    return list;
  }

  function updateMapSelect() {
    if (!mapData || !mapData.maps) return;

    const filteredMaps = getSortedMapsForMode(activeModeId);
    mapSelect.innerHTML = '';

    filteredMaps.forEach(m => {
      const opt = document.createElement('option');
      opt.value = m.id;
      opt.textContent = m.name;
      mapSelect.appendChild(opt);
    });

    if (filteredMaps.length > 0) {
      const stillExists = activeMap && filteredMaps.some(m => m.id === activeMap.id);
      if (!stillExists) {
        setMap(filteredMaps[0]);
      } else {
        updateSelectedMapCard();
      }
    } else {
      setMap(null);
    }
    renderMapPalette();
  }

