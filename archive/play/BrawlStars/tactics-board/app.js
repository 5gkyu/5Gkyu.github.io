  // ---- 検索・フィルター・並び順 ----
  function filterPalette() {
    const query = searchInput ? searchInput.value.trim().toLowerCase() : '';
    const activeChip = document.querySelector('.vp-chip.active');
    const filterRarity = activeChip ? activeChip.dataset.filterRarity : 'all';

    let filtered = allBrawlers.filter(b => {
      if (filterRarity !== 'all' && String(b.rarityLevel) !== filterRarity) {
        return false;
      }
      if (!query) return true;
      const matchName = (b.name || '').toLowerCase().includes(query);
      const matchEn = (b.name_en || '').toLowerCase().includes(query);
      const matchAlias = (b.alias || '').toLowerCase().includes(query);
      return matchName || matchEn || matchAlias;
    });

    // 公式レア度順ソート（レア度昇順 → 同一レア度内は公式order昇順）
    filtered.sort((a, b) => {
      if (a.rarityLevel !== b.rarityLevel) {
        return a.rarityLevel - b.rarityLevel;
      }
      return (a.order || 999) - (b.order || 999);
    });

    renderPalette(filtered);
  }

