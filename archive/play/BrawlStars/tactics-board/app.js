    // ---- 下部カードトレイのなめらかな慣性スクロール（イージング制御） ----
    const scrollControllers = new Map();

    function setupSmoothHorizontalScroll(container) {
      if (!container) return;

      let targetScroll = container.scrollLeft;
      let animId = null;

      const smoothStep = () => {
        const current = container.scrollLeft;
        const diff = targetScroll - current;
        if (Math.abs(diff) > 0.4) {
          // 毎フレーム差分の16%ずつ追従（滑らかに減速・イージング）
          container.scrollLeft = current + diff * 0.16;
          animId = requestAnimationFrame(smoothStep);
        } else {
          container.scrollLeft = targetScroll;
          animId = null;
        }
      };

      const addScroll = (delta) => {
        if (!animId) {
          targetScroll = container.scrollLeft;
        }
        const maxScroll = Math.max(0, container.scrollWidth - container.clientWidth);
        targetScroll = Math.max(0, Math.min(maxScroll, targetScroll + delta));

        if (!animId) {
          animId = requestAnimationFrame(smoothStep);
        }
      };

      container.addEventListener('wheel', (e) => {
        const isVertical = Math.abs(e.deltaY) > Math.abs(e.deltaX);
        const delta = isVertical ? e.deltaY * 1.5 : e.deltaX * 1.2;
        if (delta === 0) return;

        e.preventDefault();
        addScroll(delta);
      }, { passive: false });

      scrollControllers.set(container, {
        scrollBy: (amount) => addScroll(amount)
      });
    }

    [paletteGrid, mapsGrid, markersGrid].forEach(c => setupSmoothHorizontalScroll(c));

    const getActiveScrollContainer = () => {
      if (paletteGrid && paletteGrid.style.display !== 'none') return paletteGrid;
      if (mapsGrid && mapsGrid.style.display !== 'none') return mapsGrid;
      return markersGrid;
    };

