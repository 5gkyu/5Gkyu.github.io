  // ---- データ読み込み ----
  async function loadData() {
    try {
      // 1. マップ＆キャラクター総合データ（共通 brawl-data.json）取得
      let mapsRes = await fetch(BRAWL_MASTER_DATA_URL);
      if (!mapsRes.ok) {
        mapsRes = await fetch(FALLBACK_DATA_URL);
      }
      if (mapsRes.ok) {
        mapData = await mapsRes.json();
        // image-data-full.json 内の brawlers をロード（1ファイルで完結可能）
        if (mapData.brawlers && Array.isArray(mapData.brawlers)) {
          allBrawlers = mapData.brawlers
            .filter(b => {
              const n = (b.name || '') + (b.name_en || '');
              return !n.includes('バズ・ライトイヤー') && !n.includes('バズライトイヤー');
            })
            .map(b => {
              let imgName = b.image || '';
              if (imgName === 'c-51kaze.png' || b.name === 'カゼ') {
                imgName = 'c-51-kaze.png';
              }
              return {
                id: b.id,
                name: b.name,
                name_en: b.name_en || b.name,
                yomi: b.yomi || b.name,
                image: imgName,
                rarityLevel: b.rarityLevel || b.rarity_id || 2,
                rarityName: b.rarity || b.rarity_name || 'レア',
                alias: b.alias || '',
                order: b.order || 999
              };
            });
        }
      }

      // 2. brawl-firebase の最新マスターがあれば更新・マージ
      try {
        const brawlersRes = await fetch(BRAWLERS_DATA_URL);
        if (brawlersRes.ok) {
          const rawList = await brawlersRes.json();
          allBrawlers = rawList
            .filter(b => {
              const n = (b.name || '') + (b.name_en || '');
              return !n.includes('バズ・ライトイヤー') && !n.includes('バズライトイヤー');
            })
            .map(b => {
              let imgName = b.image || '';
              if (imgName === 'c-51kaze.png' || b.name === 'カゼ') {
                imgName = 'c-51-kaze.png';
              }
              const existing = (mapData && mapData.brawlers) ? mapData.brawlers.find(x => x.name === b.name) : null;
              return {
                id: b.id,
                name: b.name,
                name_en: b.name_en || b.name,
                yomi: (existing && existing.yomi) || b.name,
                image: imgName,
                rarityLevel: b.rarity_id || (existing && existing.rarityLevel) || 2,
                rarityName: b.rarity_name || (existing && existing.rarity) || 'レア',
                alias: b.alias || '',
                order: b.order || (existing && existing.order) || 999
              };
            });
        }
      } catch (fbErr) {
        // brawlers.json が無くても image-data-full.json 1ファイルのみで動作可能
        console.warn('brawlers.json 取得スキップ（image-data-full.json のデータを使用）:', fbErr);
      }

      populateModes();
      filterPalette();
      renderMapPalette();
      renderMarkers();
    } catch (err) {
      console.error('データ読み込みエラー:', err);
    }
  }

