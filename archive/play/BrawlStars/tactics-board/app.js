  // 履歴（Undo / Redo）スタック
  const undoStack = [];
  const redoStack = [];
  const MAX_HISTORY = 40;

  function saveUndoSnapshot() {
    undoStack.push({
      pieces: JSON.parse(JSON.stringify(pieces)),
      drawStrokes: JSON.parse(JSON.stringify(drawStrokes))
    });
    if (undoStack.length > MAX_HISTORY) undoStack.shift();
    redoStack.length = 0; // 新規操作でRedoスタックをクリア
  }

  function undo() {
    if (undoStack.length === 0) return;
    redoStack.push({
      pieces: JSON.parse(JSON.stringify(pieces)),
      drawStrokes: JSON.parse(JSON.stringify(drawStrokes))
    });
    const state = undoStack.pop();
    pieces = state.pieces;
    drawStrokes = state.drawStrokes;
    renderPieces();
    redrawStrokes();
  }

  function redo() {
    if (redoStack.length === 0) return;
    undoStack.push({
      pieces: JSON.parse(JSON.stringify(pieces)),
      drawStrokes: JSON.parse(JSON.stringify(drawStrokes))
    });
    const state = redoStack.pop();
    pieces = state.pieces;
    drawStrokes = state.drawStrokes;
    renderPieces();
    redrawStrokes();
  }

